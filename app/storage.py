"""Private media storage: validated, checksummed and encrypted at rest.

Files live under random keys (never user-supplied names), encrypted client-side, and are
only served back through authorized API endpoints. STORAGE_BACKEND=local writes to
MEDIA_ROOT (dev); STORAGE_BACKEND=s3 uses a private S3 bucket (AWS / multi-instance).
"""
from __future__ import annotations

import hashlib
import logging
import os
import uuid
from pathlib import Path

from cryptography.fernet import Fernet

from .config import get_settings

log = logging.getLogger(__name__)

# Magic-number signatures so a renamed executable cannot pose as an image.
_SIGNATURES: dict[str, tuple[bytes, ...]] = {
    "image/jpeg": (b"\xff\xd8\xff",),
    "image/png": (b"\x89PNG\r\n\x1a\n",),
    "image/gif": (b"GIF87a", b"GIF89a"),
    "image/webp": (b"RIFF",),
    "image/heic": (),
    "application/pdf": (b"%PDF",),
    "video/mp4": (),
    "video/quicktime": (),
    "video/webm": (b"\x1a\x45\xdf\xa3",),
    "text/plain": (),
}

_KIND = {"image/": "image", "video/": "video", "application/pdf": "document", "text/plain": "document"}


class UploadRejected(ValueError):
    pass


def classify(mime: str) -> str:
    for prefix, kind in _KIND.items():
        if mime.startswith(prefix):
            return kind
    raise UploadRejected(f"Unsupported file type: {mime}")


def validate_upload(filename: str, mime: str, data: bytes) -> str:
    settings = get_settings()
    if mime not in _SIGNATURES:
        raise UploadRejected(f"Unsupported file type: {mime}")
    if not data:
        raise UploadRejected(f"{filename} is empty")
    if len(data) > settings.max_upload_mb * 1024 * 1024:
        raise UploadRejected(f"{filename} exceeds {settings.max_upload_mb} MB")
    sigs = _SIGNATURES[mime]
    if sigs and not any(data.startswith(s) for s in sigs):
        raise UploadRejected(f"{filename} content does not match declared type {mime}")
    if mime in ("video/mp4", "video/quicktime") and data[4:8] != b"ftyp":
        raise UploadRejected(f"{filename} is not a valid MP4/MOV file")
    if mime == "text/plain":
        try:
            data.decode("utf-8")
        except UnicodeDecodeError as exc:
            raise UploadRejected(f"{filename} is not UTF-8 text") from exc
    return classify(mime)


class LocalEncryptedStore:
    def __init__(self, root: Path, key: str):
        self.root = root
        self.root.mkdir(parents=True, exist_ok=True)
        if not key:
            key_file = root / ".dev-media-key"
            if not key_file.exists():
                log.warning("MEDIA_ENCRYPTION_KEY not set - generating a dev key at %s", key_file)
                key_file.write_bytes(Fernet.generate_key())
                key_file.chmod(0o600)
            key = key_file.read_text().strip()
        self.fernet = Fernet(key.encode())

    def _path(self, key: str) -> Path:
        # Keys are generated by us (uuid hex); reject anything else defensively.
        if not all(c in "0123456789abcdef/" for c in key) or ".." in key:
            raise ValueError("invalid storage key")
        return self.root / key

    def put(self, data: bytes) -> tuple[str, str]:
        key = f"{uuid.uuid4().hex[:2]}/{uuid.uuid4().hex}"
        path = self._path(key)
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_bytes(self.fernet.encrypt(data))
        path.chmod(0o600)
        return key, hashlib.sha256(data).hexdigest()

    def get(self, key: str, expected_sha256: str | None = None) -> bytes:
        data = self.fernet.decrypt(self._path(key).read_bytes())
        if expected_sha256 and hashlib.sha256(data).hexdigest() != expected_sha256:
            raise IOError(f"checksum mismatch for {key}")
        return data


class S3EncryptedStore:
    """Private S3 bucket. Objects are Fernet-encrypted client-side *and* stored with SSE-KMS
    (or SSE-S3 when no key id is given). The bucket should block all public access."""

    def __init__(self, bucket: str, prefix: str, key: str, kms_key_id: str | None = None,
                 region: str | None = None, endpoint_url: str | None = None):
        import boto3
        if not key:
            raise RuntimeError("MEDIA_ENCRYPTION_KEY is required when STORAGE_BACKEND=s3")
        self.bucket, self.prefix, self.kms_key_id = bucket, prefix.strip("/"), kms_key_id
        self.fernet = Fernet(key.encode())
        self.s3 = boto3.client("s3", region_name=region, endpoint_url=endpoint_url or None)

    def _key(self, key: str) -> str:
        if not all(c in "0123456789abcdef/" for c in key) or ".." in key:
            raise ValueError("invalid storage key")
        return f"{self.prefix}/{key}" if self.prefix else key

    def put(self, data: bytes) -> tuple[str, str]:
        key = f"{uuid.uuid4().hex[:2]}/{uuid.uuid4().hex}"
        extra = ({"ServerSideEncryption": "aws:kms", "SSEKMSKeyId": self.kms_key_id} if self.kms_key_id
                 else {"ServerSideEncryption": "AES256"})
        self.s3.put_object(Bucket=self.bucket, Key=self._key(key), Body=self.fernet.encrypt(data),
                           ContentType="application/octet-stream", **extra)
        return key, hashlib.sha256(data).hexdigest()

    def get(self, key: str, expected_sha256: str | None = None) -> bytes:
        body = self.s3.get_object(Bucket=self.bucket, Key=self._key(key))["Body"].read()
        data = self.fernet.decrypt(body)
        if expected_sha256 and hashlib.sha256(data).hexdigest() != expected_sha256:
            raise IOError(f"checksum mismatch for {key}")
        return data


_store: LocalEncryptedStore | S3EncryptedStore | None = None


def get_store() -> LocalEncryptedStore | S3EncryptedStore:
    """STORAGE_BACKEND=local (dev, single host) or s3 (AWS / any multi-instance deploy)."""
    global _store
    if _store is None:
        s = get_settings()
        if os.getenv("STORAGE_BACKEND", "local").lower() == "s3":
            _store = S3EncryptedStore(os.environ["S3_BUCKET"], os.getenv("S3_PREFIX", "media"),
                                      s.media_encryption_key, os.getenv("S3_KMS_KEY_ID") or None,
                                      os.getenv("AWS_REGION"), os.getenv("S3_ENDPOINT_URL"))
        else:
            _store = LocalEncryptedStore(s.media_root, s.media_encryption_key)
    return _store
